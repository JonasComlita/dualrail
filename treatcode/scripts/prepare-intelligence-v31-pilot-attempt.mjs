import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const argument = (name) => process.argv.find((value) => value.startsWith(`--${name}=`))?.slice(name.length + 3);
const taskId = argument("task");
const model = argument("model");
const effort = argument("effort");
const runId = argument("run");
if (!/^TC-V31-PILOT-\d{3}$/.test(taskId || "") || !/^[A-Za-z0-9._-]+$/.test(model || "") || !/^[A-Za-z0-9._-]+$/.test(effort || "") || !/^[A-Za-z0-9._-]+$/.test(runId || "")) throw new Error("usage: --task=TC-V31-PILOT-NNN --model=<id> --effort=<level> --run=<id>");
const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(appRoot, "..");
const source = path.join(repoRoot, "benchmarks", "intelligence-v3.1", "pilots", taskId, "participant");
const attemptRoot = path.join(repoRoot, "build", "intelligence-v31-pilot-runs", runId, taskId, `${model}-${effort}`);
if (fs.existsSync(attemptRoot)) throw new Error(`fresh attempt path already exists: ${attemptRoot}`);
fs.mkdirSync(attemptRoot, { recursive: true });
fs.cpSync(source, path.join(attemptRoot, "baseline"), { recursive: true });
fs.cpSync(source, path.join(attemptRoot, "submission"), { recursive: true });
fs.writeFileSync(path.join(attemptRoot, "attempt.json"), `${JSON.stringify({ schema: "treatcode.intelligence.pilot-subject-attempt.v3.1", official: false, run_id: runId, task_id: taskId, model, reasoning_effort: effort, fresh_context: true, cross_task_memory_disabled: true, clock_started_before_task_release: true, released_at: new Date().toISOString(), status: "released" }, null, 2)}\n`, { flag: "wx" });
fs.writeFileSync(path.join(attemptRoot, "discussion.md"), "", { flag: "wx" });
console.log(JSON.stringify({ task_id: taskId, model, reasoning_effort: effort, attempt_root: attemptRoot, submission_root: path.join(attemptRoot, "submission"), discussion_path: path.join(attemptRoot, "discussion.md") }));
